def build_catalog():
    figures = []
    n = 1
    for fam_id, fam_en, fam_zh in FAMILIES:
        for slug, en, zh, kind, legacy in RAW[fam_id]:
            figures.append({
                "id": f"{n:03d}",
                "slug": slug,
                "en": en,
                "zh": zh,
                "family": fam_id,
                "family_en": fam_en,
                "family_zh": fam_zh,
                "kind": kind,
                "legacy": legacy,
            })
            n += 1
    slugs = [f["slug"] for f in figures]
    if len(slugs) != len(set(slugs)):
        dup = sorted({s for s in slugs if slugs.count(s) > 1})
        raise ValueError(f"duplicate slugs: {dup}")
    if len(figures) != 300:
        raise ValueError(f"expected 300 figures, got {len(figures)}")
    return figures


FIGURES = build_catalog()
